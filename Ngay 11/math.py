import math

# Hằng số
print(f"Pi: {math.pi}")
print(f"E: {math.e}")

# làm tròn
x = 4.7
print(f"Làm tròn lên: {x} = {math.ceil(x)}") # làm tròn lên dùng ceil
print(f"Làm tròn xuống: {x} = {math.floor(x)}") # làm tròn lên dùng floor

# Căn bậc và lũy thừa
print(f"Căn bậc 2 của 16 là: {int(math.sqrt(16))}")
print(f"2 mũ 10 bằng: {math.pow(2, 10)}")